const ejecutar = async () => {
    try {
        await conectarDB();

        const productosLimpios = productos.map((producto) => ({
            ...producto,
            caracteristicas: (producto.caracteristicas || [])
                .map((caracteristica) => caracteristica.trim().replace(/^[-–—•]\s*/, ''))
                .filter(Boolean)
        }));

        const nombresActuales = productosLimpios.map((producto) => producto.nombre);
        const eliminados = await Producto.deleteMany({ nombre: { $nin: nombresActuales } });

        let creados = 0;
        let actualizados = 0;

        for (const producto of productosLimpios) {
            const resultado = await Producto.updateOne(
                { nombre: producto.nombre },
                { $set: producto },
                { upsert: true, runValidators: true, setDefaultsOnInsert: true }
            );

            if (resultado.upsertedCount > 0) creados += 1;
            else actualizados += 1;
        }

        console.log(`Productos eliminados: ${eliminados.deletedCount}`);
        console.log(`Productos actualizados: ${actualizados}`);
        console.log(`Productos creados: ${creados}`);
        process.exit(0);
    } catch (error) {
        console.error('Error al cargar los productos:', error.message);
        process.exit(1);
    }
};

ejecutar();
